    def _interpolar_valor(self, tabela, peso, kg_adicional=None):
        """Interpola valor para um peso específico"""
        pesos = sorted(tabela.keys())
        
        if peso <= pesos[0]:
            return tabela[pesos[0]]
        
        if peso >= pesos[-1]:
            if kg_adicional is not None:
                return round(tabela[pesos[-1]] + (peso - pesos[-1]) * kg_adicional, 2)
            return tabela[pesos[-1]]
        
        for i in range(len(pesos) - 1):
            if pesos[i] <= peso <= pesos[i + 1]:
                prop = (peso - pesos[i]) / (pesos[i + 1] - pesos[i])
                valor = tabela[pesos[i]] + (tabela[pesos[i + 1]] - tabela[pesos[i]]) * prop
                return round(valor, 2)
        
        return None
    
